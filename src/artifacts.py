"""Formatting leftovers in human vs machine texts: how often each pattern occurs, per label and domain (issue #32).

    python -m src.artifacts            # full data -> results/artifacts.md
    python -m src.artifacts --dev      # dev sample -> results_dev/artifacts.md (< 1 min)

Why: TF-IDF's strongest "human" features are not writing style but leftovers of the web pages the human texts were
scraped from (results/tfidf_lr/indist/top_features.csv): the Wikipedia section titles "References", "External links"
and "See also", Reddit's link placeholder `_URL_0_`, and the punctuation ". ," / ",," left in wikiHow texts where
the step titles were cut out (e.g. "...the speed you want. , You do not want..."). If a pattern is common in human texts and almost absent from machine texts, a supervised detector can
use it as a shortcut: it learns *where a text came from*, not *who wrote it*. This script puts numbers on that.

For every pattern (a regular expression, below) and every domain it reports the share of human texts and of machine
texts that contain the pattern at least once. Input: src.data.load_texts() (paraphrased texts, ids ending in
`_para`, are left out: they are not M4 texts). Output: a Markdown file with one overall table and one per-domain table.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import pandas as pd

from src.data import DOMAINS, ROOT, load_texts

# name -> regex. Each one is a top "human" TF-IDF feature (or, for LaTeX, a leftover seen in the error analysis).
PATTERNS: dict[str, str] = {
    "references": r"(?i)\breferences\b",                 # Wikipedia section title / arXiv-PeerRead mentions
    "external links": r"(?i)\bexternal links\b",         # Wikipedia section title
    "see also": r"(?i)\bsee also\b",                     # Wikipedia section title
    "_URL_N_": r"(?i)_url_\d+_",                         # Reddit ELI5 link placeholder (stored as _URL_0_)
    "'. ,' (stray comma)": r"\. ,",                      # wikiHow: where the bold step titles were cut out
    "',,' (double comma)": r",\s*,",                     # wikiHow: several cut step titles in a row
    "'<year> births'": r"\b\d{3,4} births\b",            # Wikipedia category line
    "LaTeX math '$...$'": r"\$[^$\n]{1,200}\$",         # inline math in arXiv abstracts
}


def contains(texts: pd.Series, pattern: str) -> pd.Series:
    """Boolean Series: does each text contain the pattern at least once?"""
    rx = re.compile(pattern)
    return texts.map(lambda t: rx.search(t) is not None)


ANY_LEFTOVER = "any page leftover (all above except LaTeX)"
PAGE_LEFTOVERS = [p for p in PATTERNS if not p.startswith("LaTeX")]


def pattern_shares(df: pd.DataFrame, patterns: dict[str, str] = PATTERNS) -> pd.DataFrame:
    """Long table: pattern, domain ('all' + each domain), label, n texts, n with the pattern, share.

    Takes a DataFrame with text, label (0 human, 1 machine) and domain columns, as returned by load_texts().
    With the default patterns it adds one more row group, ANY_LEFTOVER: texts with at least one page leftover
    (LaTeX is left out of it because math is real content of an abstract, not a scraping leftover).
    """
    hits = {name: contains(df["text"], rx) for name, rx in patterns.items()}
    if patterns is PATTERNS:
        hits[ANY_LEFTOVER] = pd.concat([hits[p] for p in PAGE_LEFTOVERS], axis=1).any(axis=1)
    rows = []
    for name, hit in hits.items():
        for dom in ["all"] + [d for d in DOMAINS if d in set(df["domain"])]:
            in_dom = df["domain"].eq(dom) if dom != "all" else pd.Series(True, index=df.index)
            for label in (0, 1):
                mask = in_dom & df["label"].eq(label)
                n, k = int(mask.sum()), int((hit & mask).sum())
                rows.append({"pattern": name, "domain": dom, "label": label, "n": n, "n_with": k,
                             "share": k / n if n else float("nan")})
    return pd.DataFrame(rows)


def _pct(x: float) -> str:
    return "–" if pd.isna(x) else f"{100 * x:.1f}%"


def to_markdown(shares: pd.DataFrame, source: str) -> str:
    """Overall table (human %, machine %, ratio) and a pattern x domain table of 'human% / machine%'."""
    s = shares.set_index(["pattern", "domain", "label"])
    pats = list(dict.fromkeys(shares["pattern"]))
    doms = [d for d in dict.fromkeys(shares["domain"]) if d != "all"]
    n_h, n_m = s.loc[(pats[0], "all", 0), "n"], s.loc[(pats[0], "all", 1), "n"]

    lines = [f"# Formatting leftovers in human vs machine texts (generated by `python -m src.artifacts` from {source})",
             "", "Share of texts that contain each pattern at least once. Regexes are in `src/artifacts.py`.", "",
             f"## All domains ({n_h:,} human, {n_m:,} machine texts)", "",
             "| pattern | human | machine | human / machine |", "|---|---|---|---|"]
    for p in pats:
        h, m = s.loc[(p, "all", 0), "share"], s.loc[(p, "all", 1), "share"]
        ratio = "∞" if m == 0 and h > 0 else ("–" if m == 0 else f"{h / m:.1f}×")
        lines.append(f"| {p} | {_pct(h)} | {_pct(m)} | {ratio} |")
    lines += ["", "## Per domain (human % / machine %)", "",
              "| pattern | " + " | ".join(doms) + " |", "|---|" + "---|" * len(doms)]
    for p in pats:
        cells = [f"{_pct(s.loc[(p, d, 0), 'share'])} / {_pct(s.loc[(p, d, 1), 'share'])}" for d in doms]
        lines.append(f"| {p} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dev", action="store_true", help="data/sample_dev.parquet, output to results_dev/")
    ap.add_argument("--out", type=Path, help="default: results/artifacts.md (results_dev/artifacts.md with --dev)")
    a = ap.parse_args(argv)

    df = load_texts(dev=a.dev)
    df = df[~df["id"].str.endswith("_para")]     # only original M4 texts
    out = a.out or ROOT / ("results_dev" if a.dev else "results") / "artifacts.md"
    text = to_markdown(pattern_shares(df), "the dev sample" if a.dev else "data/processed/m4_en.parquet")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print(text)
    print(f"wrote {out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
